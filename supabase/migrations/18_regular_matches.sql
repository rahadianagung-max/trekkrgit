-- Trekkr Regular Match (Oct 2026) — player-created matches. Additive only.
-- A player creates a match (own court booking), others join within the
-- creator's rating range; results count toward ELO only after a player from the
-- opposing team confirms (48 h window). Only the API (service key) touches these
-- tables; RLS is on with no policies, like the other app tables.
create table if not exists public.regular_matches (
  id bigint generated by default as identity primary key,
  code text unique not null,
  creator_name text not null,
  creator_user_id text,
  title text,
  venue text not null,
  venue_registered boolean default false,
  area text,
  date text not null,
  start_time text,
  end_time text,
  format text not null default 'individual',      -- individual | fixed
  gender text not null default 'Open',            -- Men | Women | Mixed | Open
  max_players int not null default 4,
  min_rating int,
  max_rating int,
  price_per_player int,
  visibility text not null default 'public',      -- public | private
  note text,
  status text not null default 'open',            -- open | pending_confirm | confirmed | disputed | expired | cancelled
  games jsonb,
  submitted_by text,
  submitted_at timestamptz,
  confirmed_by text,
  confirmed_at timestamptz,
  disputed_by text,
  session_id text,
  created_at timestamptz not null default now()
);
create table if not exists public.regular_match_players (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.regular_matches(id) on delete cascade,
  player_name text not null,
  display text,
  gender text,
  status text not null default 'joined',          -- joined | left | removed
  joined_at timestamptz not null default now()
);
create index if not exists regular_matches_status_date on public.regular_matches(status, date);
create index if not exists regular_match_players_match on public.regular_match_players(match_id);
create index if not exists regular_match_players_name on public.regular_match_players(lower(player_name));
alter table public.regular_matches enable row level security;
alter table public.regular_match_players enable row level security;
